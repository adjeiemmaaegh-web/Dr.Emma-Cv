/* E30: deterministic, non-destructive visual-only build atop the verified E29
 * HTTPS app. Neither CV schema nor E28 JavaScript processing is rewritten. */
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const at=p=>path.join(root,p);
const sha=v=>crypto.createHash('sha256').update(v).digest('hex');
const pinnedE29='c04684c7ff79cae0068a8e44408b25b86a751d08d14909cdd1006cedefcc8767';
const deploymentConfig=JSON.parse(fs.readFileSync(at('vercel.json'),'utf8'));
assert(['node tools/build-e30-ui.mjs','node tools/build-e31-unified-ux.mjs'].includes(deploymentConfig.buildCommand),'Unexpected Vercel build command');
assert.equal(deploymentConfig.outputDirectory,'site','Vercel must publish E30 static output');
const run=spawnSync(process.execPath,['tools/build-e29-vercel.mjs'],{cwd:root,stdio:'inherit',timeout:180000});
if(run.error)throw run.error;
assert.equal(run.status,0,'Frozen E29 hosted build failed');
const file=at('site/index.html');
const baseline=fs.readFileSync(file);
assert.equal(sha(baseline),pinnedE29,'Unverified E29 source HTML: refuse UI rewrite');
const css=fs.readFileSync(at('src/styles/e30-design-system.css'),'utf8');
const js=fs.readFileSync(at('src/features/ui/e30-tools.inline.js'),'utf8');
new vm.Script(js,{filename:'e30-tools.inline.js'});
assert(css.includes('@media print')&&css.includes('.e30-tools-dock')&&css.includes('.upload-drop'));
assert(!/<\/(?:style|script)>/i.test(css),'CSS has script/style terminator');
assert(!/<\/script>/i.test(js),'JavaScript has script terminator');
let html=baseline.toString('utf8');
const head=html.indexOf('</head>'),body=html.lastIndexOf('</body>');
assert(head>0&&head<500000&&body>html.length-30000,'Unexpected HTML boundaries');
html=html.slice(0,head)+'<style id="ledger-e30-design-system">\n'+css+'\n</style>\n'+html.slice(head);
const tail=html.lastIndexOf('</body>');
html=html.slice(0,tail)+'<script id="ledger-e30-tools-consolidation">\n'+js+'\n</script>\n'+html.slice(tail);
assert.equal(html.split('ledger-e30-design-system').length,2);
assert.equal(html.split('ledger-e30-tools-consolidation').length,2);
assert(!/<script\b[^>]+\bsrc\s*=/i.test(html),'External JavaScript is forbidden');
fs.writeFileSync(file,html);
const hash=sha(Buffer.from(html,'utf8'));
assert.equal(hash,'1dd5b058bc10e058825e37ec0de706f42efe2ac89c602a87909672f948dc546c','E30 output checksum changed without review');
const swfile=at('site/sw.js');
let sw=fs.readFileSync(swfile,'utf8');
assert(/ledger-e29-[a-f0-9]{14}/.test(sw),'Unexpected service worker version');
sw=sw.replace(/ledger-e29-[a-f0-9]{14}/g,'ledger-e29-'+hash.slice(0,14));
fs.writeFileSync(swfile,sw);
const original=JSON.parse(fs.readFileSync(at('site/site-integrity.json'),'utf8'));
assert.equal(original.hostedHtmlSha256,pinnedE29);
original.version='E30 unified visual design system based on E29';
original.sourceE29Sha256=pinnedE29;
original.hostedHtmlSha256=hash;
original.hostedHtmlBytes=Buffer.byteLength(html);
original.designOnly=true;
original.criticalBehaviorPreserved=['CV data schema','trained OCR and PDF parsing','Word/PDF exports','job and calendar workflows','template document canvas','local browser storage'];
original.status='UX/UI engineering verified by automated browser QA; owner production acceptance still pending';
fs.writeFileSync(at('site/site-integrity.json'),JSON.stringify(original,null,2)+'\n');
console.log('E30 hosted UI:',JSON.stringify({htmlSha256:hash,htmlBytes:Buffer.byteLength(html),sourceE29Sha256:pinnedE29,designOnly:true}));
