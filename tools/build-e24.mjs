import assert from 'node:assert/strict';
import fs from 'node:fs';
import crypto from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const sha=s=>crypto.createHash('sha256').update(s).digest('hex');
const frozen='development/e23/Ledger_CV_Studio_E23_Calendar_Import_Safety.html';
const output='development/e24/Ledger_CV_Studio_E24_Offline_Calendar_Timezones.html';
const component='src/features/calendar/ics-import.inline.js';
const prev=read(frozen),next=read(output),module=read(component);
assert.equal(sha(prev),'5ad2e0ee3171502a4e5c0720ef9becf49ab97e791b3ba6affd0364e5f7bc8807','E23 changed unexpectedly');
const opening='/* E20 career calendar import:',closing='/* E3 career workspace.';
const start=prev.indexOf(opening),end=prev.indexOf(closing,start);
assert(start>=0&&end>start&&prev.indexOf(opening,start+1)<0,'Ambiguous calendar module boundary');
assert(module.startsWith(opening)&&module.includes('E24: all calendar parsing remains local'));
assert(module.includes('global.ledgerE20Calendar={parse,merge,taskId};'));
new vm.Script(module,{filename:component});
const rebuilt=prev.slice(0,start)+module+prev.slice(end);
assert.equal(rebuilt,next,'E24 application does not match one-module source rebuild');
assert.equal(sha(next),'4d99390d87619839374b60b22220241557f7a6fb966567ea637c8fae5625d52d','Pinned E24 standalone checksum mismatch');
assert.equal(rebuilt.slice(0,start),prev.slice(0,start),'Non-calendar prefix drift');
assert.equal(rebuilt.slice(start+module.length),prev.slice(end),'Non-calendar suffix drift');
const scripts=[...next.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].filter(x=>x[1].trim());
for(let i=0;i<scripts.length;i++)new vm.Script(scripts[i][1],{filename:'e24-inline-'+i+'.js'});
assert(!/<script\b[^>]+\bsrc\s*=/i.test(next),'Unexpected external script dependency');
assert(!/<link\b[^>]+\brel\s*=\s*["']stylesheet["'][^>]+\bhref\s*=/i.test(next),'Unexpected external stylesheet dependency');
fs.mkdirSync(path.join(root,'dist'),{recursive:true});
fs.writeFileSync(path.join(root,'dist',path.basename(output)),rebuilt);
console.log('PASS: E24 modular calendar source rebuild matches frozen standalone HTML');
console.log('PASS: '+scripts.length+' embedded scripts syntax parsed; no external JS/CSS dependency');
console.log('E24 app SHA-256: '+sha(next));
console.log('Status: DEVELOPMENT CANDIDATE; production NO-GO');
