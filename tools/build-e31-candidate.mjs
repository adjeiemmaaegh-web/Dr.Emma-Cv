/* E31 candidate builder: frozen E30 first, additive E31 second.
 * This file is NOT the Vercel production build command. */
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const at=p=>path.join(root,p);
const sha=b=>crypto.createHash('sha256').update(b).digest('hex');
const expectedE30='1dd5b058bc10e058825e37ec0de706f42efe2ac89c602a87909672f948dc546c';
const config=JSON.parse(fs.readFileSync(at('vercel.json'),'utf8'));
assert.equal(config.buildCommand,'node tools/build-e30-ui.mjs','Production must remain pinned to E30');
const run=spawnSync(process.execPath,['tools/build-e30-ui.mjs'],{cwd:root,stdio:'inherit',timeout:180000});
if(run.error)throw run.error;
assert.equal(run.status,0,'E30 frozen builder failed');
const htmlPath=at('site/index.html');
let html=fs.readFileSync(htmlPath,'utf8');
assert.equal(sha(Buffer.from(html)),expectedE30,'E30 build unexpectedly changed');
const css=fs.readFileSync(at('src/styles/e31-accessibility.css'),'utf8');
const js=fs.readFileSync(at('src/features/ui/e31-keyboard.inline.js'),'utf8');
new vm.Script(js,{filename:'e31-keyboard.inline.js'});
assert(!/<\/(?:style|script)>/i.test(css),'Unexpected CSS terminator');
assert(!/<\/script>/i.test(js),'Unexpected JS terminator');
assert(css.includes('@media print')&&css.includes('forced-colors:active'),'Required E31 CSS missing');
assert(js.includes('focusout')&&js.includes('aria-labelledby'),'Required E31 keyboard semantics missing');
assert(!html.includes('ledger-e31-accessibility'),'E31 styles already injected');
assert(!html.includes('ledger-e31-keyboard'),'E31 script already injected');
html=html.replace('</head>','<style id="ledger-e31-accessibility">\n'+css+'\n</style>\n</head>');
const tail=html.lastIndexOf('</body>');
assert(tail>=0,'No closing body');
html=html.slice(0,tail)+'<script id="ledger-e31-keyboard">\n'+js+'\n</script>\n'+html.slice(tail);
const bytes=Buffer.from(html,'utf8'),digest=sha(bytes);
fs.writeFileSync(htmlPath,bytes);
const swPath=at('site/sw.js');
let sw=fs.readFileSync(swPath,'utf8');
assert(sw.includes('ledger-e29-'+expectedE30.slice(0,14)),'Unexpected E30 service worker cache');
sw=sw.replaceAll('ledger-e29-'+expectedE30.slice(0,14),'ledger-e31-'+digest.slice(0,14));
fs.writeFileSync(swPath,sw);
const manifestPath=at('site/site-integrity.json');
const manifest=JSON.parse(fs.readFileSync(manifestPath,'utf8'));
assert.equal(manifest.hostedHtmlSha256,expectedE30);
manifest.version='E31 accessibility engineering candidate based on frozen E30';
manifest.sourceE30Sha256=expectedE30;
manifest.hostedHtmlSha256=digest;
manifest.hostedHtmlBytes=bytes.length;
manifest.status='E31 engineering candidate; automated and device acceptance pending; not deployed';
fs.writeFileSync(manifestPath,JSON.stringify(manifest,null,2)+'\n');
console.log(JSON.stringify({version:'E31 candidate',htmlSha256:digest,htmlBytes:bytes.length,sourceE30Sha256:expectedE30}));
